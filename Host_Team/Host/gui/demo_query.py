"""
demo_query.py — Offline demo backend for the VICA Host GUI.

This module is *only* used by ``demo_start_app.py``. The production entry
point (``s1_start_app.py``) does not import anything from here, so deleting
this file alongside ``demo_start_app.py`` cleanly removes every trace of demo
mode from the project.

WHAT IT DOES
────────────
``DemoBackend`` implements the same duck-typed interface as ``MqttBackend``
in ``s1_start_app.py``:

    set_on_packet(callback)                # register inbound-packet callback
    send_discovery_request()               # fakes a discovery_response packet
    send_query_request(text, target_devices=None) -> str
                                           # fakes per-target query_response packets
    close()

The GUI is unaware which backend it's talking to — every fake packet has the
exact wire-shape of a real MQTT packet, so the same ``_on_packet`` handler in
``run_app`` renders both real and fake traffic identically.

DEMO FLOW (offline, no broker required)
───────────────────────────────────────
1. Run:           python demo_start_app.py
2. Click:         "Discover"        →  4 fake edge devices appear
3. Check boxes:   pick 1+ devices    →  chips appear in the Query window
4. Type a query → Send                →  one fake response per target arrives,
                                          staggered so the multi-device
                                          targeting feature is visibly active.
"""

