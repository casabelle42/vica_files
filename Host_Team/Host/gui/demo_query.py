# ── PNG builder (no Pillow / third-party deps) ───────────────────────────────
def _make_colored_png_b64(r: int, g: int, b: int,
                          width: int = 240, height: int = 160) -> str:
    """Return a base64-encoded solid-colour PNG built from raw bytes only."""

    def _chunk(tag: bytes, data: bytes) -> bytes:
        crc = zlib.crc32(tag + data) & 0xFFFF_FFFF
        return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", crc)

    row = b"\x00" + bytes([r, g, b] * width)   # filter byte 0 + RGB pixels
    raw = row * height
    sig  = b"\x89PNG\r\n\x1a\n"
    ihdr = _chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0))
    idat = _chunk(b"IDAT", zlib.compress(raw, 6))
    iend = _chunk(b"IEND", b"")
    return base64.b64encode(sig + ihdr + idat + iend).decode()


# ── DemoBackend ──────────────────────────────────────────────────────────────
class DemoBackend:
    """Offline replacement for ``MqttBackend`` — fakes every edge / server hop.

    The backend never touches the network. It synthesises packets in the same
    shape that real edges produce and pushes them through whatever
    ``on_packet`` callback the GUI registered, so every code path in
    ``run_app`` exercises with no special-casing.
    """

    DISCOVERY_DELAY_SEC      = 0.2    # tiny pause before the fake response
    QUERY_FIRST_DELAY_SEC    = 1.5    # how soon the first response shows up
    QUERY_PER_TARGET_GAP_SEC = 0.7    # stagger between successive responses

    def __init__(self, devices: Optional[List[dict]] = None) -> None:
        self._on_packet: Optional[Callable[[Dict[str, Any]], None]] = None
        # Take a fresh copy so the caller can safely mutate the original.
        self._devices: List[dict] = [dict(d) for d in (devices or DUMMY_DEVICES)]

    # ── HostBackend interface ────────────────────────────────────────────────
    def set_on_packet(self, callback: Callable[[Dict[str, Any]], None]) -> None:
        self._on_packet = callback

    def send_command(self, cmd: dict,
                     reply_topic: Optional[str] = None,
                     timeout: Optional[float] = None) -> dict:
        """Mirror ``HostCommandSender.send_command`` for offline demo use.

        Only ``{"command": "discover"}`` is meaningful — it synthesises the
        same packet shape a real broker would return. The packet is *also*
        delivered through the registered ``on_packet`` callback, so both
        update paths in ``run_app`` (the worker's emit and ``_on_packet``'s
        emit) fire exactly as they would against a real broker.
        """
        command = (cmd or {}).get("command")
        if command == "discover":
            # Brief sleep so the worker thread blocks like the real one would.
            time.sleep(min(self.DISCOVERY_DELAY_SEC, float(timeout or 10.0)))
            pkt = self._build_discovery_packet()
            self._emit(pkt)             # ← maintains the original 2-path UI update
            return pkt
        return {}

    def send_query_request(self, query_text: str,
                           target_devices: Optional[List[str]] = None,
                           model: Optional[str] = None,
                           query_id: Optional[str] = None,
                           video: Optional[str] = None) -> str:
        query_id = query_id or f"demo-{uuid.uuid4().hex[:8]}"
        targets = [t for t in (target_devices or []) if isinstance(t, str) and t.strip()]
        model_note = f", model={model!r}" if model else ""
        if video:
            model_note += f", video={video!r}"

        if not targets:
            # Broadcast — single response from a generic source name.
            threading.Timer(
                self.QUERY_FIRST_DELAY_SEC,
                self._emit_query_response,
                args=("demo-edge-01", query_text, query_id, video),
            ).start()
            print(f"[DEMO] Queued broadcast query_response (query_id={query_id}{model_note})")
            return query_id

        for i, target in enumerate(targets):
            delay = self.QUERY_FIRST_DELAY_SEC + i * self.QUERY_PER_TARGET_GAP_SEC
            threading.Timer(
                delay, self._emit_query_response, args=(target, query_text, query_id, video)
            ).start()
        print(f"[DEMO] Queued {len(targets)} fake response(s) for "
              f"query_id={query_id}{model_note} → {', '.join(targets)}")
        return query_id

    def close(self) -> None:
        # No persistent resources; daemon timers die with the process.
        self._on_packet = None

    # ── packet emitters ──────────────────────────────────────────────────────
    def _emit(self, pkt: Dict[str, Any]) -> None:
        cb = self._on_packet
        if not cb:
            print("[DEMO] Drop packet — no on_packet callback registered.")
            return
        try:
            cb(pkt)
        except Exception as e:
            print(f"[DEMO] on_packet callback raised: {e!r}")

    def _build_discovery_packet(self) -> Dict[str, Any]:
        """Construct a discovery_response packet identical in shape to one
        a real broker would deliver."""
        pkt = {
            "header": {
                "message_type": "discovery_response",
                "source_device": "demo-broker",
                "timestamp": datetime.now().isoformat()[:19],
                "message_id": str(uuid.uuid4()),
            },
            "body": {
                "devices": [dict(d) for d in self._devices],
            },
        }
        print(f"[DEMO] Built discovery_response with {len(self._devices)} device(s).")
        return pkt

    def _emit_query_response(self, source_device: str,
                             query_text: str, query_id: str,
                             video: Optional[str] = None) -> None:
        r = random.randint(40, 220)
        g = random.randint(40, 220)
        b = random.randint(40, 220)
        image_b64 = _make_colored_png_b64(r, g, b)
        description = random.choice(_DESCRIPTIONS)
        timestamp = datetime.now().isoformat()[:19]

        pkt = {
            "header": {
                "message_type": "query_response",
                "source_device": source_device,
                "timestamp": timestamp,
                "message_id": str(uuid.uuid4()),
            },
            "body": {
                "query_id": query_id,
                "answer": f"[{source_device}] {description}  (query sent at {timestamp})",
                "metadata": {
                    "image_base64": image_b64,
                    "chunk_index":  0,
                    "total_chunks": 1,
                    # Echo the source back like a real edge does.
                    "source": "video" if video else "camera",
                    "video": video or None,
                },
                "frame": {"detections": []},
            },
        }
        print(f"[DEMO] Emitting query_response from '{source_device}' for "
              f"query_id={query_id}: '{query_text}'")
        self._emit(pkt)


