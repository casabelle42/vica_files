import json
import queue
import threading
import time
import os
import paho.mqtt.client as mqtt
from handler import EdgeHandler, edge_device_name

class MQTTEdgeClient:
    """
    Lightweight MQTT client:
    - Routes incoming MQTT messages to EdgeHandler
    - Publishes outgoing messages generated by the handler

    Inference is intentionally NOT run inside the MQTT callback thread.
    Blocking the paho network loop with VLM inference causes broker
    disconnects / missed publishes that look like "network issues".
    """

    def __init__(self, mqtt_broker="localhost", mqtt_port=1883):
        self.mqtt_broker = mqtt_broker
        self.mqtt_port = mqtt_port

        # Thread-safe queues for outgoing publishes and inbound work.
        self.outgoing_queue = queue.Queue()
        # Bound inbound work so a stuck inference path cannot grow forever.
        self.incoming_queue = queue.Queue(maxsize=32)

        # Must match discovery name and handler targeted-query filter.
        self.device_name = edge_device_name()

        self._stop = threading.Event()
        self._worker_thread = None

        # Instantiate the handler
        self.edge_handler = EdgeHandler(on_update_callback=self._on_handler_update)

        # MQTT setup
        self.mqtt_client = mqtt.Client()
        self.mqtt_client.on_connect = self._on_mqtt_connect
        self.mqtt_client.on_message = self._on_mqtt_message
        self.mqtt_client.on_disconnect = self._on_mqtt_disconnect

    # ------------------------
    # Handler callback
    # ------------------------
    def _on_handler_update(self, update_type, data):
        """
        Called by EdgeHandler whenever there's an outgoing packet.
        Routes to the correct MQTT topic and queues for publishing.
        """
        if update_type in ("device_status", "container_status"):
            topic = "edge/status"
        else:
            topic = "edge/results"
        self.outgoing_queue.put((topic, data))

    # ------------------------
    # MQTT callbacks
    # ------------------------
    def _on_mqtt_connect(self, client, userdata, flags, rc):
        if rc == 0:
            print(f"[MQTTEdgeClient] ✅ Connected to broker {self.mqtt_broker}:{self.mqtt_port}")
            print(f"[MQTTEdgeClient] Device identity for targeting: {self.device_name!r}")
            # Subscribe to device-specific topic for targeted queries (NUC routes here)
            device_topic = f"edge/{self.device_name}/control"
            client.subscribe(device_topic)
            print(f"[MQTTEdgeClient] Subscribed to topic '{device_topic}'")
            # Subscribe to broadcast topic when host sends without target_devices
            client.subscribe("edge/control")
            print("[MQTTEdgeClient] Subscribed to topic 'edge/control' (broadcast)")
        else:
            print(f"[MQTTEdgeClient] ❌ Connection failed with code {rc}")

    def _on_mqtt_disconnect(self, client, userdata, rc):
        # rc==0 is a clean disconnect; anything else means the broker/network dropped us.
        if rc != 0:
            print(f"[MQTTEdgeClient] Unexpected disconnect rc={rc}; paho will auto-reconnect")
        else:
            print("[MQTTEdgeClient] Disconnected from broker")

    def _on_mqtt_message(self, client, userdata, msg):
        """
        Receive MQTT message quickly and hand off to the worker thread.
        Never run inference here — it stalls the MQTT network loop.
        """
        try:
            payload_str = msg.payload.decode()
            print(f"[MQTTEdgeClient] Received MQTT message on {msg.topic}: {payload_str[:300]}")
            try:
                self.incoming_queue.put_nowait((msg.topic, payload_str))
            except queue.Full:
                print(
                    "[MQTTEdgeClient] Incoming queue full — dropping oldest query "
                    "so the MQTT loop stays responsive"
                )
                try:
                    self.incoming_queue.get_nowait()
                except queue.Empty:
                    pass
                try:
                    self.incoming_queue.put_nowait((msg.topic, payload_str))
                except queue.Full:
                    print("[MQTTEdgeClient] Dropped message — worker still saturated")
        except Exception as e:
            print(f"[MQTTEdgeClient] Error handling incoming MQTT message: {e}")

    def _worker_loop(self):
        """Process queued queries off the MQTT network thread."""
        while not self._stop.is_set():
            try:
                _topic, payload_str = self.incoming_queue.get(timeout=0.25)
            except queue.Empty:
                continue
            try:
                self.edge_handler.process_query(payload_str)
            except Exception as e:
                print(f"[MQTTEdgeClient] Worker error processing query: {e}")

    # ------------------------
    # Publish outgoing messages
    # ------------------------
    def _publish_outgoing(self):
        """
        Publish packets queued by the handler to their designated MQTT topics.
        Uses get_nowait to avoid empty()/get() races across threads.
        """
        while True:
            try:
                topic, packet = self.outgoing_queue.get_nowait()
            except queue.Empty:
                break
            try:
                payload_str = json.dumps(packet, separators=(",", ":"), ensure_ascii=False)
                result = self.mqtt_client.publish(topic, payload_str)
                if getattr(result, "rc", 0) != 0:
                    print(f"[MQTTEdgeClient] Publish rc={result.rc} topic={topic}")
                else:
                    print(f"[MQTTEdgeClient] Published to {topic}: {payload_str[:200]}...")
            except Exception as e:
                print(f"[MQTTEdgeClient] Error publishing message: {e}")

    # ------------------------
    # Start / stop
    # ------------------------
    def start(self):
        self._stop.clear()
        self._worker_thread = threading.Thread(
            target=self._worker_loop, name="edge-query-worker", daemon=True
        )
        self._worker_thread.start()

        try:
            self.mqtt_client.connect(self.mqtt_broker, self.mqtt_port, 60)
            self.mqtt_client.loop_start()
            print("[MQTTEdgeClient] Listening for messages...")

            while not self._stop.is_set():
                self._publish_outgoing()
                time.sleep(0.05)

        except KeyboardInterrupt:
            print("[MQTTEdgeClient] Stopping client...")
        except Exception as e:
            print(f"[MQTTEdgeClient] Error: {e}")
        finally:
            self.stop()

    def stop(self):
        """Stop worker, handler, and MQTT cleanly (no socket / thread leaks)."""
        if self._stop.is_set() and (
            self._worker_thread is None or not self._worker_thread.is_alive()
        ):
            return
        self._stop.set()
        try:
            self.edge_handler.stop()
        except Exception as e:
            print(f"[MQTTEdgeClient] Error stopping handler: {e}")
        if self._worker_thread and self._worker_thread.is_alive():
            self._worker_thread.join(timeout=3)
        try:
            self.mqtt_client.loop_stop()
        except Exception:
            pass
        try:
            self.mqtt_client.disconnect()
        except Exception:
            pass
        print("[MQTTEdgeClient] Stopped.")


# ------------------------
# Run the client
# ------------------------
if __name__ == "__main__":
    # Default to the NUC broker; allow override via env var.
    # Default: Vector lab broker (10.148.1.35). Override with VICA_MQTT_BROKER / VICA_MQTT_PORT.
    MQTT_BROKER_IP = os.environ.get("VICA_MQTT_BROKER", "10.148.1.35")
    MQTT_BROKER_PORT = int(os.environ.get("VICA_MQTT_PORT", "1883"))
    print(
        f"[MQTTEdgeClient] Device identity: {edge_device_name()!r} "
        f"(broker {MQTT_BROKER_IP}:{MQTT_BROKER_PORT}, topic edge/<name>/control)"
    )
    client = MQTTEdgeClient(mqtt_broker=MQTT_BROKER_IP, mqtt_port=MQTT_BROKER_PORT)
    client.start()
