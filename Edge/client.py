import json
import queue
import time
import paho.mqtt.client as mqtt
from handler import EdgeHandler  # Make sure your handler is in the same directory

class MQTTEdgeClient:
    """
    Lightweight MQTT client:
    - Routes incoming MQTT messages to EdgeHandler
    - Publishes outgoing messages generated by the handler
    """

    def __init__(self, mqtt_broker="localhost", mqtt_port=1883):
        self.mqtt_broker = mqtt_broker
        self.mqtt_port = mqtt_port

        # Thread-safe queue for outgoing messages from handler
        self.outgoing_queue = queue.Queue()

        # Instantiate the handler
        self.edge_handler = EdgeHandler(on_update_callback=self._on_handler_update)

        # MQTT setup
        self.mqtt_client = mqtt.Client()
        self.mqtt_client.on_connect = self._on_mqtt_connect
        self.mqtt_client.on_message = self._on_mqtt_message

    # ------------------------
    # Handler callback
    # ------------------------
    def _on_handler_update(self, update_type, data):
        """
        Called by EdgeHandler whenever there's an update.
        Simply queue updates for publishing via MQTT.
        """
        # Prepare a payload for MQTT
        payload = {
            "type": update_type,
            "data": data
        }
        # Put it in the outgoing queue
        self.outgoing_queue.put(payload)

    # ------------------------
    # MQTT callbacks
    # ------------------------
    def _on_mqtt_connect(self, client, userdata, flags, rc):
        if rc == 0:
            print(f"[MQTTEdgeClient] Connected to broker {self.mqtt_broker}:{self.mqtt_port}")
            client.subscribe("edge/control")
            print("[MQTTEdgeClient] Subscribed to topic 'edge/control'")
        else:
            print(f"[MQTTEdgeClient] Connection failed with code {rc}")

    def _on_mqtt_message(self, client, userdata, msg):
        """
        Receive MQTT message and forward to EdgeHandler
        """
        try:
            payload_str = msg.payload.decode()
            print(f"[MQTTEdgeClient] Received MQTT message on {msg.topic}: {payload_str}")
            try:
                payload = json.loads(payload_str)
            except json.JSONDecodeError:
                payload = payload_str  # fallback: send raw string

            # Forward to handler and capture response
            response_json = self.edge_handler.handle_command(payload)

            # Publish response directly to reply_topic if provided, else to edge/results
            if response_json:
                try:
                    response_dict = json.loads(response_json)
                except json.JSONDecodeError:
                    response_dict = {"raw": response_json}

                reply_topic = None
                if isinstance(payload, dict):
                    reply_topic = payload.get("reply_topic")

                if reply_topic:
                    try:
                        self.mqtt_client.publish(reply_topic, json.dumps(response_dict))
                        print(f"[MQTTEdgeClient] Published reply to {reply_topic}")
                    except Exception as e:
                        print(f"[MQTTEdgeClient] Error publishing reply_topic response: {e}")
                else:
                    self._on_handler_update("handler_response", response_dict)

        except Exception as e:
            print(f"[MQTTEdgeClient] Error handling incoming MQTT message: {e}")

    # ------------------------
    # Publish outgoing messages
    # ------------------------
    def _publish_outgoing(self):
        """
        Publish messages queued by the handler to MQTT topic 'edge/results'
        """
        while not self.outgoing_queue.empty():
            payload = self.outgoing_queue.get()
            try:
                payload_str = json.dumps(payload, separators=(",", ":"), ensure_ascii=False)
                self.mqtt_client.publish("edge/results", payload_str)
                print(f"[MQTTEdgeClient] Published: {payload_str[:200]}...")
            except Exception as e:
                print(f"[MQTTEdgeClient] Error publishing message: {e}")

    # ------------------------
    # Start MQTT client loop
    # ------------------------
    def start(self):
        try:
            self.mqtt_client.connect(self.mqtt_broker, self.mqtt_port, 60)
            self.mqtt_client.loop_start()
            print("[MQTTEdgeClient] Listening for messages...")

            while True:
                self._publish_outgoing()
                time.sleep(0.05)

        except KeyboardInterrupt:
            print("[MQTTEdgeClient] Stopping client...")
        except Exception as e:
            print(f"[MQTTEdgeClient] Error: {e}")


# ------------------------
# Run the client
# ------------------------
if __name__ == "__main__":
    MQTT_BROKER_IP = "localhost"  # PLACEHOLDER FOR THE NUC'S IP ADDR, NEED TO INPUT PORT AS WELL
    client = MQTTEdgeClient(mqtt_broker=MQTT_BROKER_IP)
    client.start()
